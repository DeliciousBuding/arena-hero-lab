"""Field-by-field parity of the Python leaderboard producer against the pinned
golden output of the legacy TypeScript conversion.

The golden fixture ``tests/fixtures/leaderboard/legacy-ts-golden.json`` was
generated by running the legacy conversion (not hand-written):

    pnpm --dir apps/leaderboard-web exec tsx scripts/convert.mts \
      --source=<repo>/apps/leaderboard-web/scripts/input/results.json \
      --output=<repo>/packages/arena-hero-bench/tests/fixtures/leaderboard/legacy-ts-golden.json \
      --converted-at=2026-01-01T00:00:00Z --source-label=fixtures/benchmark-v3

The comparison walks the full document field by field: keys and array lengths
must match exactly, strings/booleans/null must be equal, and every numeric
field must agree within ``NUMERIC_TOLERANCE`` (1e-9).
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from arena_hero_bench.leaderboard_data import produce_leaderboard_data

WORKSPACE_ROOT = Path(__file__).resolve().parents[3]
FIXTURE = WORKSPACE_ROOT / "apps" / "leaderboard-web" / "scripts" / "input" / "results.json"
GOLDEN = Path(__file__).parent / "fixtures" / "leaderboard" / "legacy-ts-golden.json"
FIXED_TIME = "2026-01-01T00:00:00Z"
FIXED_SOURCE = "fixtures/benchmark-v3"
NUMERIC_TOLERANCE = 1e-9


def _assert_field_parity(actual: Any, expected: Any, path: str) -> None:
    if isinstance(actual, bool) or isinstance(expected, bool):
        assert isinstance(actual, bool) and isinstance(expected, bool), (
            f"{path}: bool type mismatch ({type(actual).__name__} vs {type(expected).__name__})"
        )
        assert actual == expected, f"{path}: bool mismatch {actual!r} != {expected!r}"
        return
    if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):
        assert math.isclose(actual, expected, rel_tol=0.0, abs_tol=NUMERIC_TOLERANCE), (
            f"{path}: numeric mismatch |{actual} - {expected}| > {NUMERIC_TOLERANCE}"
        )
        return
    if isinstance(actual, str) or isinstance(expected, str):
        assert isinstance(actual, str) and isinstance(expected, str), (
            f"{path}: string type mismatch ({type(actual).__name__} vs {type(expected).__name__})"
        )
        assert actual == expected, f"{path}: string mismatch {actual!r} != {expected!r}"
        return
    if actual is None or expected is None:
        assert actual is None and expected is None, (
            f"{path}: null mismatch ({actual!r} vs {expected!r})"
        )
        return
    if isinstance(actual, list) or isinstance(expected, list):
        assert isinstance(actual, list) and isinstance(expected, list), (
            f"{path}: list type mismatch ({type(actual).__name__} vs {type(expected).__name__})"
        )
        assert len(actual) == len(expected), (
            f"{path}: length mismatch {len(actual)} != {len(expected)}"
        )
        for index, (item, golden_item) in enumerate(zip(actual, expected, strict=True)):
            _assert_field_parity(item, golden_item, f"{path}[{index}]")
        return
    if isinstance(actual, dict) or isinstance(expected, dict):
        assert isinstance(actual, dict) and isinstance(expected, dict), (
            f"{path}: object type mismatch ({type(actual).__name__} vs {type(expected).__name__})"
        )
        assert set(actual) == set(expected), (
            f"{path}: key mismatch {sorted(actual)} vs {sorted(expected)}"
        )
        for key in expected:
            _assert_field_parity(actual[key], expected[key], f"{path}.{key}")
        return
    assert actual == expected, f"{path}: value mismatch {actual!r} != {expected!r}"


def test_python_producer_matches_legacy_ts_golden_field_by_field() -> None:
    raw = json.loads(FIXTURE.read_text(encoding="utf-8"))
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))

    actual = produce_leaderboard_data(
        raw,
        source_label=FIXED_SOURCE,
        converted_at=FIXED_TIME,
    )

    assert golden["schema"] == actual["schema"]
    assert golden["convertedAt"] == FIXED_TIME
    _assert_field_parity(actual, golden, "<root>")


def test_legacy_ts_golden_has_expected_scope() -> None:
    """Guard the golden fixture stays in sync with the shared input fixture."""
    raw = json.loads(FIXTURE.read_text(encoding="utf-8"))
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))

    assert len(golden["contestants"]) == len(raw["contestants"])
    assert [scenario["name"] for scenario in golden["scenarios"]] == [
        scenario["name"] for scenario in raw["scenarios"]
    ]
    assert len(golden["leaderboard"]) == len(raw["leaderboard"]) + len(
        raw.get("leaderboardControl", [])
    )
    assert sum(len(scenario["matches"]) for scenario in golden["scenarios"]) == sum(
        len(scenario["matches"]) for scenario in raw["scenarios"]
    )
